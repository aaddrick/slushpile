class Skill(NamedTuple):
    """One skill, and how each surface names it.

    Four surfaces, four voices: the Cursor skill router, the shorter always-on
    Cursor rule, the README's command list, and the snippet INSTALL.md tells a
    user to paste. They are separate fields rather than one label because they
    are read in different places at different lengths, and collapsing them would
    make every surface read like the least specific one.

    `rule` may be None, which keeps the skill out of the always-on rule. That is
    a decision recorded here, not an omission nobody notices.

    `runs` names the skills this one dispatches on the user's behalf, and it is
    declared rather than grepped out of the prose. A skill file names another
    skill for two different reasons — "run this next" and "this is your
    prerequisite" — and only the first is a call. Grepping would read
    application-builder's pointer back at job-board-search as the pipeline
    running backwards. What is declared here is then verified against the file.

    `anytime` marks a skill that is neither a pipeline stage nor called by one.
    Without it such a skill falls into the spine by default and the README tells
    the user to run it in sequence, which is wrong for anything advisory.

    Any label may use {agents}/{Agents} and {blind}/{Blind}: the number of review
    personas, and how many of them run blind, spelled out.
    """

    name: str
    cursor: str
    rule: str | None
    readme: tuple[str, ...]
    install: str
    runs: tuple[str, ...] = ()
    anytime: bool = False


