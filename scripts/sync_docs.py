def spell(count: int) -> str:
    return NUMBER_WORDS.get(count, str(count))


ORDINALS = {7: "seventh", 8: "eighth", 9: "ninth"}


def plain(agent: str) -> str:
    """The agent's name without its namespace prefix, lowercase."""
    return agent.removeprefix("slushpile-").replace("-", " ")


def agent_model(name: str) -> str | None:
    """The `model` an agent's frontmatter declares, or None if it declares none."""
    block = FRONTMATTER_BLOCK.match(
        (ROOT / "agents" / f"{name}.md").read_text(encoding="utf-8")
    )
    if not block:
        return None
    found = MODEL_FIELD.search(block.group(1))
    return found.group(1) if found else None


def display(agent: str) -> str:
    return AGENT_DISPLAY.get(agent, plain(agent))


def titled(agent: str) -> str:
    """Display name with a leading capital, leaving an initialism alone."""
    name = display(agent)
    return name[0].upper() + name[1:]


def require_exact(declared: list[str], found: set[str], label: str) -> None:
    """Fail unless the declared list names every item on disk, once each.

    This is the check that makes the whole generator worth having. Without it, a
    skill added to `skills/` and not added here disappears from the router, the
    README, and the Gemini context file, and nothing reports it.
    """
    seen: set[str] = set()
    repeated: set[str] = set()
    for name in declared:
        if name in seen:
            repeated.add(name)
        seen.add(name)

    problems = []
    if missing := sorted(found - seen):
        problems.append(f"on disk but not listed: {', '.join(missing)}")
    if unknown := sorted(seen - found):
        problems.append(f"listed but not on disk: {', '.join(unknown)}")
    if repeated:
        problems.append(f"listed twice: {', '.join(sorted(repeated))}")
    if problems:
        raise ValueError(f"{label}: " + "; ".join(problems))


class Facts:
    """Everything the generated files claim, read from where it is true."""

    def __init__(self) -> None:
        on_disk = {p.parent.name for p in (ROOT / "skills").glob("*/SKILL.md")}
        if not on_disk:
            raise ValueError("skills/: no SKILL.md files found")

        self.agents = sorted(p.stem for p in (ROOT / "agents").glob("*.md"))
        if not self.agents:
            raise ValueError("agents/: no agent definitions found")

        self.dispatch, self.blind, self.sequential = self._read_dispatch()

        # Whatever is defined but not dispatched by the review is a voice agent:
        # generated per person, named after its author, listed last.
        self.voice = [name for name in self.agents if name not in set(self.dispatch)]
        if not self.voice:
            raise ValueError("agents/: no voice agent, so no skill can draft prose")

        require_exact(
            [skill.name for skill in SKILLS], on_disk, "SKILLS in scripts/sync_docs.py"
        )
        require_exact(
            list(REVIEWERS), set(self.dispatch), "REVIEWERS in scripts/sync_docs.py"
        )
        self.skills = SKILLS
        self.spine, self.called, self.anytime, self.caller = self._read_call_graph()

    def _read_call_graph(self) -> tuple[list[Skill], list[Skill], list[Skill], str]:
        """Split the skills into the spine, what the spine calls, and the rest.

        The README separates the commands a user types from the ones a pipeline
        stage dispatches for them, because a reader who thinks all seven are
        theirs to run will run the review by hand after the builder already ran
        it twice.

        Every declared edge is verified against the caller's SKILL.md. That is
        the check worth having: delete the humanize step from the builder and
        this fails, instead of leaving the README promising a call that no
        longer happens.
        """
        declared = {skill.name for skill in SKILLS}
        callers: dict[str, list[str]] = {}
        for skill in SKILLS:
            if not skill.runs:
                continue
            body = (ROOT / "skills" / skill.name / "SKILL.md").read_text(encoding="utf-8")
            for target in skill.runs:
                if target == skill.name:
                    raise ValueError(f"SKILLS: {skill.name} lists itself in runs")
                if target not in declared:
                    raise ValueError(
                        f"SKILLS: {skill.name} runs {target}, which is not a declared skill"
                    )
                if f"/slushpile:{target}" not in body:
                    raise ValueError(
                        f"skills/{skill.name}/SKILL.md: SKILLS says it runs {target}, "
                        f"but the file never invokes /slushpile:{target}. Either the "
                        f"call was removed and `runs` did not follow, or it never "
                        f"existed."
                    )
                callers.setdefault(target, []).append(skill.name)

        called = [skill for skill in SKILLS if skill.name in callers]
        anytime = [skill for skill in SKILLS if skill.anytime]
        spine = [
            skill for skill in SKILLS if skill.name not in callers and not skill.anytime
        ]

        if overlap := sorted(skill.name for skill in anytime if skill.name in callers):
            raise ValueError(
                f"SKILLS: {', '.join(overlap)} is both called by another skill and "
                f"flagged anytime. A skill belongs to exactly one README group."
            )
        if not spine:
            raise ValueError("SKILLS: every skill is called or anytime, leaving no spine")
        if not called:
            raise ValueError(
                "SKILLS: no skill declares `runs`, so the README has nothing to "
                "separate the spine from"
            )

        # The generated prose names one caller and says it dispatches all of
        # them. Two callers would need a sentence this script does not know how
        # to write, so it fails here rather than naming one and hiding the other.
        named = sorted({name for names in callers.values() for name in names})
        if len(named) != 1:
            raise ValueError(
                f"SKILLS: {', '.join(named)} all dispatch other skills, but the "
                f"README prose is written for exactly one caller. Update "
                f"readme_pipeline() to describe the new shape."
            )
        return spine, called, anytime, named[0]

    def _read_dispatch(self) -> tuple[list[str], list[str], list[str]]:
        path = ROOT / DISPATCH_SOURCE
        rows = []
        for line in path.read_text(encoding="utf-8").splitlines():
            match = DISPATCH_ROW.match(line.strip())
            if match:
                rows.append(
                    (
                        int(match.group(1)),
                        match.group(2),
                        match.group(3).strip(),
                        match.group(4).strip(),
                    )
                )
        if not rows:
            raise ValueError(f"{DISPATCH_SOURCE}: no `| N | `slushpile-*` |` dispatch rows")

        numbers = [number for number, _, _, _ in rows]
        if numbers != list(range(1, len(rows) + 1)):
            raise ValueError(
                f"{DISPATCH_SOURCE}: dispatch numbering is {numbers}, not 1..{len(rows)}"
            )

        defined = {p.stem for p in (ROOT / "agents").glob("*.md")}
        if undefined := [name for _, name, _, _ in rows if name not in defined]:
            raise ValueError(
                f"{DISPATCH_SOURCE}: dispatches {', '.join(undefined)}, "
                f"which have no definition"
            )

        # The Model column was captured and discarded for as long as it has
        # existed, which made it the one fact in this table nothing checked.
        mismatched = [
            f"{name} (table: {model or 'blank'}, definition: {agent_model(name) or 'none'})"
            for _, name, model, _ in rows
            if agent_model(name) != model
        ]
        if mismatched:
            raise ValueError(
                f"{DISPATCH_SOURCE}: the Model column disagrees with the agent "
                f"definitions it names — {'; '.join(mismatched)}. The frontmatter "
                f"is what a harness dispatches on; the column is documentation of "
                f"it. Change whichever one is wrong."
            )

        order = [name for _, name, _, _ in rows]
        blind = [name for _, name, _, stage in rows if stage == "parallel"]
        sequential = [name for _, name, _, stage in rows if stage != "parallel"]
        if not blind:
            raise ValueError(f"{DISPATCH_SOURCE}: no dispatch row runs in parallel")
        # The generated prose names the two later stages by role. Two is the
        # pipeline's shape today; a third would need sentences this script does
        # not know how to write, so it fails here rather than describing a
        # pipeline that no longer exists.
        if len(sequential) != 2:
            raise ValueError(
                f"{DISPATCH_SOURCE}: {len(sequential)} rows run after the blind stage, "
                f"but the generated prose is written for exactly 2. Update "
                f"build_cursor_skill() and the README reviewers region to describe "
                f"the new shape."
            )
        return order, blind, sequential

    @property
    def labels(self) -> dict[str, str]:
        agents, blind, skills = len(self.dispatch), len(self.blind), len(SKILLS)
        return {
            "agents": spell(agents),
            "Agents": spell(agents).capitalize(),
            "blind": spell(blind),
            "Blind": spell(blind).capitalize(),
            "skills": spell(skills),
            "Skills": spell(skills).capitalize(),
            # Every agent shipped, which is the dispatched personas plus the
            # voice agent. Prose about the product counts these; prose about the
            # review counts {agents}.
            "defined": spell(len(self.agents)),
            "Defined": spell(len(self.agents)).capitalize(),
            # The voice agent brings the shipped total one past the dispatched
            # seven, which is how the README introduces it.
            "ordinal_agents": ORDINALS.get(len(self.agents), f"{len(self.agents)}th"),
        }

    def label(self, text: str) -> str:
        return text.format(**self.labels)


def fill(text: str) -> str:
    """Reflow a paragraph to the width the hand-written files use."""
    return textwrap.fill(
        " ".join(text.split()), width=80, break_long_words=False, break_on_hyphens=False
    )


