def build_agents_md(facts: Facts, sources: dict[str, str]) -> str:
    """AGENTS.md is CLAUDE.md with a generated-file header.

    The content is identical on purpose. A harness reading AGENTS.md needs the
    same standards as one reading CLAUDE.md, and any divergence between them is
    a bug rather than a feature worth supporting.
    """
    claude_md = sources["CLAUDE.md"]
    lines = claude_md.splitlines()

    # Keep the H1 first so the file still reads as a document, then insert the
    # marker directly beneath it.
    if lines and lines[0].startswith("# "):
        head, rest = lines[0], lines[1:]
        body = "\n".join(rest).lstrip("\n")
        return f"{head}\n\n{MARKER}\n\n{body}\n"

    return f"{MARKER}\n\n{claude_md}"


