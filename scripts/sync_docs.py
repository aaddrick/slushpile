def readme_pipeline(facts: Facts) -> str:
    """The command list, grouped by who types it.

    A renamed skill leaves a documented command that fails, so the commands are
    generated. The grouping is generated for a second reason: a flat list of
    {skills} commands reads as {skills} things the user has to run, and three of
    them are things the builder already ran. That misreading costs a user two
    redundant review passes before they work out which commands are theirs.

    One column width across every block. The groups sit under separate headings
    and still read as one list, so a blurb column that shifted between them
    would look like a formatting mistake.
    """
    column = max(len(f"/slushpile:{skill.name}") for skill in facts.skills) + 2

    def block(skills: list[Skill]) -> str:
        entries = []
        for skill in skills:
            lines = [facts.label(line) for line in skill.readme]
            command = f"/slushpile:{skill.name}".ljust(column)
            rest = [" " * column + line for line in lines[1:]]
            entries.append("\n".join([f"{command}{lines[0]}"] + rest))
        return "```\n" + "\n\n".join(entries) + "\n```"

    spine, called = spell(len(facts.spine)), spell(len(facts.called))

    return "\n\n".join(
        [
            "### The main pipeline",
            fill(
                f"{spine.capitalize()} commands, in order. A search runs on these "
                f"alone."
            ),
            block(facts.spine),
            f"### The {called} it runs for you",
            fill(
                f"`/slushpile:{facts.caller}` dispatches all {called} of these "
                f"itself, in the course of building an application. Run one "
                f"directly only to work on materials this pipeline did not build "
                f"— a resume written elsewhere, a letter drafted by hand."
            ),
            block(facts.called),
            "### Any time",
            block(facts.anytime),
        ]
    )


def readme_reviewers(facts: Facts) -> str:
    rows = [(f"**{titled(name)}**", REVIEWERS[name]) for name in facts.dispatch]
    manager, contrarian = (plain(name) for name in facts.sequential)
    blind = spell(len(facts.blind))

    return "\n\n".join(
        [
            f"### The {spell(len(facts.dispatch))} reviewers",
            table(("Agent", "Simulates"), rows),
            fill(
                f"The first {blind} run in parallel and cannot see each other's "
                f"work. The {manager} sees all {blind}. The {contrarian} sees "
                f"everything, including the {manager}, and can overrule it."
            ),
        ]
    )


def docs_agent_table(facts: Facts) -> str:
    """Dispatch order, the model each agent declares, and what it simulates.

    Three facts from three places: the order comes from the dispatch table in
    the review skill, the model from each agent's own frontmatter, and the blurb
    from REVIEWERS above. Hand-written in docs/ it would be a fourth place a
    renamed agent has to reach, and the one nothing checks.
    """
    rows = [
        f"| {number} | `{name}` | {agent_model(name) or '—'} | {REVIEWERS[name]} |"
        for number, name in enumerate(facts.dispatch, 1)
    ]
    note = fill(
        f"Plus the voice agent, `{facts.voice[0]}`, which the review never "
        f"dispatches and which is named in `preferences.yaml` rather than here. "
        f"The first {spell(len(facts.blind))} run in parallel and are blind to "
        f"each other; the last two run in order."
    )
    return "\n".join(
        ["| # | Agent | Model | Simulates |", "|---|---|---|---|", *rows]
    ) + "\n\n" + note


