#!/usr/bin/env python3
"""Generate every derived documentation file from its canonical source.

Several surfaces describe this pipeline to a reader or to another model:
CLAUDE.md and its AGENTS.md mirror, the two Cursor router files, GEMINI.md,
README.md, the paste-in snippet in INSTALL.md, and the docs/ tree. Every one of
them lists the skills, and most of them state the review's shape. None of those facts is theirs to hold. They
live in `skills/`, in `agents/`, and in the dispatch table inside
`skills/adversarial-review/SKILL.md`.

A list that drifts is not a cosmetic problem. A skill missing from the Cursor
router is a stage a Cursor user cannot reach, and a reviewer reading a diff has
no way to see it. So the lists are generated, and the prose around them lives
here.

Three kinds of generated output:

**Whole files.** AGENTS.md mirrors CLAUDE.md. The two Cursor files are built
from the tree, with their framing prose in this script.

**Marked regions.** README.md, INSTALL.md, and GEMINI.md are hand-written except
between `BEGIN GENERATED` and `END GENERATED` markers. Anything inside a marked
region is overwritten on the next run.

**Count claims.** A few sentences state a number in prose, where a marked region
would be heavier than the sentence it wraps. Those are checked, not written: the
sentence must appear with the right number in it, or this script fails and names
the file.

A registered claim only covers the sentence someone thought to register, which
is the weaker half of the problem: "eight skills" sat in INSTALL.md, in the help
skill, and in the marketplace manifest through the ninth skill shipping, because
no row named those sentences. So a sweep runs alongside the claims and reads
every shipped surface for a counted noun — "nine skills", "eight agents",
"seven reviewers" — and fails on any number that is not a true count, whether or
not a row names it. The claims pin the wording of the sentences that matter; the
sweep catches the ones nobody registered.

Everything derived is looked up by name, and a name that matches nothing is an
error rather than a silent omission. That is the point. Add a skill, forget the
router, and this fails instead of shipping a pipeline with an unreachable stage.

    python3 scripts/sync_docs.py            # write the derived copies
    python3 scripts/sync_docs.py --check    # exit 1 if a copy has drifted

--check is the CI gate. A pull request that edits CLAUDE.md, adds a skill, or
reorders the review pipeline without running the generator fails there rather
than shipping files that disagree.
"""

