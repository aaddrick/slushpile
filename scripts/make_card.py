#!/usr/bin/env python3
"""Draw the cards under .github/assets/.

`hero.png` is the image at the top of README.md: the loop in three columns. The
wordmark and the hook on the left, the files the workspace keeps in the middle,
the seven reviewers on the right. Read left to right it says: here is the claim,
here is what the system holds onto, here is what attacks it. The middle column
is the argument -- every other tool in this category would have an empty one.

`hero-<tag>.png` is the same card in one of the mirror's languages, one per tag
in sync_docs.LANGUAGES, embedded by that language's README. The hero is the only
image in this repository that is mostly words, which is why it is the only one
translated: a reader who arrived in their own language otherwise meets an
English picture first and the translation second. The diagrams under
docs/diagrams/ stay English on every page and move their alt text instead,
because a translated diagram is a per-language render pipeline.

`social.png` is the file uploaded at Settings -> General -> Social preview, and
it is what LinkedIn, Signal, Teams, and Slack actually render when someone pastes
the repository link. It carries the wordmark and the hook and nothing else. It
has no translated twin because a repository has one social preview, and GitHub
picks it without knowing who is looking.

The hero and the social card exist separately because they are read at different
sizes and the same image cannot serve both. An unfurl renders around 400px wide.
At that size the hero's columns collapse into grey texture, and every earlier
attempt to fix that meant deleting detail the README wants. Splitting them ends
the argument: the hero is free to be dense because nobody sees it at 400px, and
the social card is free to be nearly empty because nobody sees it at 1280.

The right column's agents and the bar that groups the blind ones are read from
the review's dispatch table through sync_docs, not typed here. That column is a
diagram of the pipeline's shape, and a diagram of a shape the pipeline no longer
has is worse than no diagram. Every number the cards print is read from the same
place, in every language. The middle column's file list is still typed here,
because it names what onboarding writes rather than anything the tree declares --
so each name is checked against the onboard skill before the card is drawn.

Run after any change to the header text, the file list, or the agent list:

    python3 scripts/make_card.py

Both cards are 1280x640, which is GitHub's social preview size and a clean 2:1.
Anything taller loses its top and bottom edge in a preview.

Needs Pillow. It is not a test dependency, so CI does not run this and no gate
checks the committed PNGs against a fresh render. Pillow encodes the same pixels
differently across versions, so a checksum gate would fail on an unrelated
upgrade. Regenerate by hand and commit the result.

Fonts live in assets/fonts/. All are OFL; the licenses sit beside them. The
Chinese card is set in a subset of Noto Sans CJK SC carrying only the characters
that card draws, regenerated by scripts/subset_cjk_font.py -- so changing a
Chinese string here means running that script too, and this one refuses to draw
until it has been.
"""

