def draw_wordmark(d, x, y, font):
    for part, colour in WORDMARK:
        d.text((x, y), part, font=font, fill=colour)
        x += d.textlength(part, font=font)


def centred(draw, y, text, font, fill):
    draw.text(((W - draw.textlength(text, font=font)) / 2, y), text, font=font, fill=fill)


def check_languages() -> None:
    """Every language in the mirror gets a card, or this stops.

    A language added to sync_docs.LANGUAGES without a Card here would otherwise
    keep embedding the English hero, which is the one failure a translated page
    cannot show: the picture is fine, it is just somebody else's.
    """
    wanted = {language.tag for language in sync_docs.LANGUAGES}
    have = set(CARDS) - {"en"}
    if wanted != have:
        raise SystemExit(
            f"make_card.py: the mirror carries {sorted(wanted)} and CARDS covers "
            f"{sorted(have)}. Missing: {sorted(wanted - have) or 'none'}. "
            f"Unknown: {sorted(have - wanted) or 'none'}."
        )


def check_workspace() -> None:
    """FILES must be exactly the workspace, in both directions."""
    onboard = (ROOT / "skills" / "onboard" / "SKILL.md").read_text(encoding="utf-8")

    # A file the card claims the workspace keeps, that onboarding never writes,
    # is the card being wrong about the one thing it exists to claim.
    unwritten = [name for name in FILES if name not in onboard]
    if unwritten:
        raise SystemExit(
            f"make_card.py: the workspace column names {', '.join(unwritten)}, "
            f"which skills/onboard/SKILL.md never writes"
        )

    # And the other direction, which is the one that was open. The check above
    # catches a deleted file; it cannot catch a file added to the workspace and
    # never added here, which leaves the column quietly short on the one claim
    # the card exists to make.
    block = SCAFFOLD_BLOCK.search(onboard)
    if not block:
        raise SystemExit(
            "make_card.py: skills/onboard/SKILL.md no longer has the scaffold "
            "block this column is checked against. Restore it, or point "
            "SCAFFOLD_BLOCK at wherever the workspace file list moved."
        )
    unaccounted = sorted(
        set(WORKSPACE_FILE.findall(block.group(1))) - set(FILES) - set(OMITTED)
    )
    if unaccounted:
        raise SystemExit(
            f"make_card.py: onboarding writes {', '.join(unaccounted)}, which the "
            f"workspace column neither shows nor records as a deliberate "
            f"omission. Add it to FILES, or to OMITTED with the reason."
        )


def resolve(tag: str, facts: sync_docs.Facts) -> Card:
    """One language's Card with its counts filled in and its shape checked."""
    card = CARDS[tag]
    blind = len(facts.blind)
    numbers = {
        "n": len(facts.dispatch),
        "n_word": sync_docs.spell(len(facts.dispatch)),
        "N_WORD": sync_docs.spell(len(facts.dispatch)).upper(),
        "blind": blind,
        "blind_word": sync_docs.spell(blind),
        "Blind_word": sync_docs.spell(blind).capitalize(),
    }

    dispatch = [sync_docs.plain(name) for name in facts.dispatch]
    if set(dispatch) != set(card.reviewers):
        raise SystemExit(
            f"make_card.py: the {tag} card labels {sorted(card.reviewers)}, and "
            f"the review dispatches {sorted(dispatch)}. A renamed agent needs a "
            f"label in every language, or its column silently shifts by one."
        )
    if len(card.captions) != len(FILES):
        raise SystemExit(
            f"make_card.py: the {tag} card has {len(card.captions)} captions for "
            f"{len(FILES)} workspace files"
        )

    if card.script == "cjk":
        strings = [card.eyebrow, card.keep_label, card.reviewers_label,
                   *card.hook, *card.keep, *card.captions, *card.keep_note,
                   *card.blind_note, *card.reviewers.values()]
        missing = sorted({c for s in strings for c in s.format(**numbers)} - covered())
        if missing:
            raise SystemExit(
                f"make_card.py: the {tag} card draws {''.join(missing)}, which the "
                f"vendored subset does not carry. Run scripts/subset_cjk_font.py "
                f"and commit both faces with the card."
            )

    fill = lambda text: text.format(**numbers)  # noqa: E731
    return card._replace(
        eyebrow=fill(card.eyebrow),
        hook=tuple(fill(line) for line in card.hook),
        keep=tuple(fill(line) for line in card.keep),
        keep_label=fill(card.keep_label),
        keep_note=tuple(fill(line) for line in card.keep_note),
        reviewers_label=fill(card.reviewers_label),
        blind_note=tuple(fill(line) for line in card.blind_note),
    )


class Overflow:
    """Collects every line that runs past its column, and reports them together.

    A card that overflows is not subtly wrong: text crosses the hairline into
    the next column and the three-column structure the whole design rests on
    stops reading. Nothing about the drawing code can prevent it, because the
    words are written by hand in five languages and a Spanish sentence is
    reliably a third longer than the English one it translates.

    Failing on the first one would mean five runs to tune five lines, so they
    are gathered and raised at once.
    """

    def __init__(self, label: str) -> None:
        self.label = label
        self.problems: list[str] = []

    def wide(self, draw, text, font, right, where, x=0, track=0):
        over = (x + tracked_len(draw, text, font, track)) - right
        if over > 0:
            self.problems.append(f"{where}: {text!r} runs {over / S:.0f}px past its column")

    def tall(self, lines, top, step, floor, where):
        over = (top + len(lines) * step) - floor
        if over > 0:
            self.problems.append(
                f"{where}: {len(lines)} lines run {over / S:.0f}px past the space for them"
            )

    def raise_if_any(self) -> None:
        if self.problems:
            joined = "\n  ".join(self.problems)
            raise SystemExit(
                f"make_card.py: the {self.label} does not fit:\n  {joined}\n"
                f"Shorten the line or break it differently in CARDS. The columns "
                f"are fixed: whatever spills crosses into the next one."
            )


def fitted_track(draw, text, font, width, track):
    """The requested letter spacing, or the most of it that fits.

    Only the three column headings are tracked, and only they use this. Tracking
    is the one thing on the card that can absorb a longer translation without
    anyone noticing, so it gives way before the type size does.
    """
    while track > 0 and tracked_len(draw, text, font, track) > width:
        track -= 0.25
    return track


def draw_hero(d, tag: str, card: Card, facts: sync_docs.Facts):
    """A README's header image: the loop in three columns."""
    COL_M, COL_R = 580 * S, 902 * S     # middle and right column left edges
    LABEL_Y, LIST_Y, NOTE_Y = 52 * S, 104 * S, 448 * S
    HOOK_Y, HOOK_STEP = 272 * S, 40 * S
    NOTE_STEP = 26 * S
    RULES = (540 * S, 862 * S)          # the two hairlines, and the column edges
    GUTTER = 20 * S
    FOOT = 552 * S                      # the notes stop clear of the footer rule
    script = card.script

    label_font = disp(20, "SemiBold", script)
    note_font = disp(20, "Medium", script)
    over = Overflow(f"{tag} hero")

    # Two hairlines carry the three-column structure. Without them the middle and
    # right lists read as one ragged block of grey text.
    for x in RULES:
        d.rectangle([x, 44 * S, x + 1, 524 * S], fill=RULE)

    # --- left: the wordmark and the hook, verbatim from that language's README --
    track = fitted_track(d, card.eyebrow, label_font, RULES[0] - GUTTER - PAD, 2.5)
    tracked(d, (PAD, LABEL_Y), card.eyebrow, label_font, INK_MUTE, track=track)
    over.wide(d, card.eyebrow, label_font, RULES[0] - GUTTER, "eyebrow", x=PAD, track=track)

    # Sized to clear the x=540 hairline: nine mono characters at 80px is 432px
    # from a 72px margin, which leaves the column its gutter. The wordmark is a
    # name, so it is Latin on every card.
    draw_wordmark(d, PAD, 104 * S, mono(80, "Medium"))

    # The last line is the one the card exists to add, so it carries the accent.
    # In body colour it reads as a trailing clause and gets skipped at small sizes.
    tag_font = disp(36, "Medium", script)
    lines = [(line, INK_BODY) for line in card.hook] + [(line, BLUE) for line in card.keep]
    over.tall(lines, HOOK_Y, HOOK_STEP, 524 * S, "hook")
    for i, (line, colour) in enumerate(lines):
        d.text((PAD, HOOK_Y + i * HOOK_STEP), line, font=tag_font, fill=colour)
        over.wide(d, line, tag_font, RULES[0] - GUTTER, "hook", x=PAD)

    # ===========================================================================
    # Middle: the durable workspace. These are the files onboard writes and every
    # later skill reads. Adding a file to the workspace without adding it here
    # leaves the card quietly wrong.
    # ===========================================================================
    track = fitted_track(d, card.keep_label, label_font, RULES[1] - GUTTER - COL_M, 2.5)
    tracked(d, (COL_M, LABEL_Y), card.keep_label, label_font, INK_MUTE, track=track)
    over.wide(d, card.keep_label, label_font, RULES[1] - GUTTER, "keep label", x=COL_M, track=track)

    # The filenames stay mono and stay English: they are paths on the reader's
    # disk, and a translated one would be a file that does not exist.
    file_font = mono(22, "Medium")
    caption_font = disp(21, "Medium", script)
    for i, (name, caption) in enumerate(zip(FILES, card.captions)):
        y = LIST_Y + i * 72 * S
        d.rectangle([COL_M, y + 4 * S, COL_M + 3 * S, y + 24 * S], fill=BLUE_DIM)
        d.text((COL_M + 16 * S, y), name, font=file_font, fill=INK)
        d.text((COL_M + 16 * S, y + 32 * S), caption, font=caption_font, fill=INK_MUTE)
        over.wide(d, caption, caption_font, RULES[1] - GUTTER, "caption", x=COL_M + 16 * S)

    over.tall(card.keep_note, NOTE_Y, NOTE_STEP, FOOT, "workspace note")
    for i, line in enumerate(card.keep_note):
        d.text((COL_M, NOTE_Y + i * NOTE_STEP), line, font=note_font, fill=INK_MUTE)
        over.wide(d, line, note_font, RULES[1] - GUTTER, "workspace note", x=COL_M)

    # ===========================================================================
    # Right: the reviewers, in dispatch order. The bracket is the architecture --
    # the blind ones run concurrently and cannot see each other's findings, which
    # is the whole reason their agreement counts as evidence.
    # ===========================================================================
    blind = len(facts.blind)  # 1..blind run concurrently; then synthesis, then falsification
    labels = [card.reviewers[sync_docs.plain(name)] for name in facts.dispatch]

    track = fitted_track(d, card.reviewers_label, label_font, W - PAD - COL_R, 2.5)
    tracked(d, (COL_R, LABEL_Y), card.reviewers_label, label_font, INK_MUTE, track=track)
    over.wide(d, card.reviewers_label, label_font, W - PAD, "reviewers label", x=COL_R, track=track)

    agent_font = mono(20, "Medium") if card.mono_reviewers else disp(22, "Medium", script)
    rows = [LIST_Y + i * 48 * S for i in range(len(labels))]
    for y, name in zip(rows, labels):
        d.text((COL_R + 16 * S, y), name, font=agent_font, fill=INK_BODY)
        over.wide(d, name, agent_font, W - PAD, "reviewer", x=COL_R + 16 * S)

    # One bar spanning the parallel stages, then a bar each for the two that run
    # alone. The grouping is the claim; the colour change marks the new job.
    d.rectangle([COL_R, rows[0] + 4 * S, COL_R + 3 * S, rows[blind - 1] + 24 * S], fill=BLUE_DIM)
    d.rectangle([COL_R, rows[blind] + 4 * S, COL_R + 3 * S, rows[blind] + 24 * S], fill=AMBER)
    d.rectangle(
        [COL_R, rows[blind + 1] + 4 * S, COL_R + 3 * S, rows[blind + 1] + 24 * S], fill=BLUE
    )

    over.tall(card.blind_note, NOTE_Y, NOTE_STEP, FOOT, "review note")
    for i, line in enumerate(card.blind_note):
        d.text((COL_R, NOTE_Y + i * NOTE_STEP), line, font=note_font, fill=INK_MUTE)
        over.wide(d, line, note_font, W - PAD, "review note", x=COL_R)

    # --- footer ----------------------------------------------------------------
    # The hairline is load-bearing. Without it the URL reads as a fifth line of the
    # left column rather than as the card's footer.
    d.rectangle([PAD, 562 * S, W - PAD, 562 * S + 1], fill=RULE)

    # Both lines sit on one baseline. The two faces have different ascents, so a
    # shared top edge would leave them visibly off by a few pixels. Neither is
    # translated: one is a URL and the other is four product names.
    BASE = H - 44 * S
    url_font = mono(23, "Medium")
    harnesses = "CLAUDE CODE  ·  CODEX  ·  CURSOR  ·  GEMINI CLI"
    hf = disp(21, "SemiBold")
    harness_left = W - PAD - tracked_len(d, harnesses, hf, track=2.5)

    # The only row whose neighbour moves: URL anchored left, harnesses right.
    # Every other guard measures against a fixed column, so this one has to be
    # written separately or the URL grows into the harness list with no error.
    over.wide(d, URL, url_font, harness_left - FOOT_GUTTER, "footer URL", x=PAD)

    d.text((PAD, BASE - url_font.getmetrics()[0]), URL, font=url_font, fill=INK_MUTE)
    tracked(d, (harness_left, BASE - hf.getmetrics()[0]),
            harnesses, hf, (0x6E, 0x73, 0x7B), track=2.5)

    return over


def draw_social(d, card: Card):
    """The unfurl card. Read at ~400px wide, so it holds the hook and nothing else.

    Everything here is set two to three times larger than the same text on the
    hero. A 42px line survives the scale down to roughly 13px; the hero's 20px
    list items would land at 6px, which is why none of them are here.
    """
    # Everything here is centred, so a line that is too long bleeds off both
    # edges rather than into a column. Measured against the same margin the hero
    # uses, since a card cropped at 400px has no room to lose a character.
    over = Overflow("social card")

    eyebrow = disp(26, "SemiBold")
    over.wide(d, card.eyebrow, eyebrow, W - 2 * PAD, "eyebrow", track=4)
    tracked(d, ((W - tracked_len(d, card.eyebrow, eyebrow, track=4)) / 2, 138 * S),
            card.eyebrow, eyebrow, INK_MUTE, track=4)

    # Centred, so the whole wordmark is measured before it is placed.
    wordmark = mono(124, "Medium")
    total = sum(d.textlength(p, font=wordmark) for p, _ in WORDMARK)
    draw_wordmark(d, (W - total) / 2, 190 * S, wordmark)

    tag_font = disp(42, "Medium")
    for i, line in enumerate([*card.hook, *card.keep]):
        over.wide(d, line, tag_font, W - 2 * PAD, "hook line")
        centred(d, (396 + i * 48) * S, line, tag_font,
                BLUE if line in card.keep else INK_BODY)

    url_font = mono(21, "Medium")
    over.wide(d, URL, url_font, W - 2 * PAD, "URL")
    centred(d, 570 * S, URL, url_font, (0x5C, 0x63, 0x6D))

    return over


def main():
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DIR
    check_languages()
    check_workspace()
    facts = sync_docs.Facts()

    for tag in CARDS:
        card = resolve(tag, facts)
        img, d = new_card()
        draw_hero(d, tag, card, facts).raise_if_any()
        name = "hero.png" if tag == "en" else f"hero-{tag}.png"
        out = img.resize((W // S, H // S), Image.LANCZOS)
        out.save(out_dir / name, optimize=True)
        print(f"wrote {out_dir / name} {out.size[0]}x{out.size[1]}")

    img, d = new_card()
    draw_social(d, resolve("en", facts)).raise_if_any()
    out = img.resize((W // S, H // S), Image.LANCZOS)
    out.save(out_dir / "social.png", optimize=True)
    print(f"wrote {out_dir / 'social.png'} {out.size[0]}x{out.size[1]}")


if __name__ == "__main__":
    main()
