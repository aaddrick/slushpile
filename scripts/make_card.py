class Card(NamedTuple):
    """Every string one language's hero draws, and how to set them.

    Each field is a line, or a tuple of lines, rather than a paragraph the
    drawing code wraps. Wrapping would be one algorithm serving five scripts
    with different word lengths and no shared idea of where a line may break,
    and it would move the decision about what the card emphasises away from
    whoever wrote the words. The columns are narrow; every break is a choice.

    `{n}`, `{n_word}`, `{N_WORD}`, `{blind}`, `{blind_word}` and `{Blind_word}`
    are filled from the review's dispatch table. A number typed here is a number
    that goes stale the next time the pipeline's shape changes, which is the one
    kind of error a picture hides best.

    English prose spells a small number out; the mirror writes it as a digit,
    on the same rule the translated pages follow, so that a count stays
    matchable in a language whose number words nothing here knows.
    """

