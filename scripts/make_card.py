# Saira Condensed and IBM Plex Mono cover Latin, including every Vietnamese
# precomposed vowel and every Spanish and Portuguese accent. Neither has a CJK
# glyph, so the Chinese card is set in a subset of Noto Sans CJK SC instead.
CJK_STEM = "NotoSansCJKsc-Subset"
COVERAGE = FONTS / f"{CJK_STEM}.coverage.txt"
CODEPOINT = re.compile(r"^U\+([0-9A-F]{4,6})", re.MULTILINE)

# Noto ships the subset at two weights against the display face's three, and it
# is drawn a little smaller: a Han glyph fills its em square where a condensed
# Latin letter fills about half of it, so matched point sizes leave the Chinese
# card visibly heavier than the other five.
CJK_WEIGHT = {"Bold": "Bold", "SemiBold": "Bold", "Medium": "Medium"}
CJK_SCALE = 0.86


def disp(size, weight="Bold", script="latin"):
    if script == "cjk":
        return ImageFont.truetype(
            str(FONTS / f"{CJK_STEM}-{CJK_WEIGHT[weight]}.ttf"), int(size * CJK_SCALE * S)
        )
    return ImageFont.truetype(str(FONTS / f"SairaCondensed-{weight}.ttf"), int(size * S))


def mono(size, weight="Regular", script="latin"):
    if script == "cjk":
        return ImageFont.truetype(
            str(FONTS / f"{CJK_STEM}-{CJK_WEIGHT[weight]}.ttf"), int(size * CJK_SCALE * S)
        )
    return ImageFont.truetype(str(FONTS / f"IBMPlexMono-{weight}.ttf"), int(size * S))


def covered() -> set[str]:
    """The characters the vendored CJK subset actually carries.

    A missing glyph does not fail: it draws .notdef, which is a blank or a box,
    and a card of blanks looks like a rendering bug rather than like a string
    somebody edited without re-running the subsetter. So the strings are checked
    against the manifest the subsetter writes before anything is drawn.
    """
    if not COVERAGE.is_file():
        raise SystemExit(
            f"make_card.py: {COVERAGE.relative_to(ROOT)} is missing, so there is "
            f"no way to tell whether the CJK subset covers the Chinese card. "
            f"Run scripts/subset_cjk_font.py."
        )
    text = COVERAGE.read_text(encoding="utf-8")
    return {chr(int(code, 16)) for code in CODEPOINT.findall(text)}


def new_card():
    """A dark canvas with the faint dot grid both cards share."""
    img = Image.new("RGB", (W, H), CANVAS)
    d = ImageDraw.Draw(img)
    for gy in range(0, H, 24 * S):
        for gx in range(0, W, 24 * S):
            d.point((gx, gy), fill=(0x16, 0x1B, 0x22))
    return img, d


def tracked(draw, xy, text, font, fill, track=0):
    """Draw text with letter spacing. Returns the end x."""
    x, y = xy
    for ch in text:
        draw.text((x, y), ch, font=font, fill=fill)
        x += draw.textlength(ch, font=font) + track * S
    return x


def tracked_len(draw, text, font, track=0):
    return sum(draw.textlength(c, font=font) + track * S for c in text)


